"""
DPO Dataset Generator
=====================
Generates a DPO (Direct Preference Optimization) dataset from the existing SFT data.

Strategy:
- chosen:   high-quality completions from energy_data_structured.jsonl
- rejected: responses generated by the BASE model (without any fine-tuning)

The base model's raw outputs are "worse" — they are generic, vague, contain
hallucinated numbers, or miss the specific facts present in the chosen answers.
This teaches the fine-tuned model to prefer precise, factual answers over
the generic outputs of the vanilla base model.

Usage:
    python create_dpo_dataset.py [--model MODEL_ID] [--limit N] [--output FILE]
"""

import os
import json
import argparse
import torch
from tqdm import tqdm
from transformers import AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig

# ── Config ────────────────────────────────────────────────────────────────────
DEFAULT_MODEL_ID   = "microsoft/Phi-3-mini-4k-instruct"   # base model for rejected
_ROOT               = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
INPUT_JSONL         = os.path.join(_ROOT, "data", "energy_data_structured.jsonl")
OUTPUT_JSONL        = os.path.join(_ROOT, "data", "energy_data_dpo.jsonl")
MAX_SEQ_LENGTH      = 512   # keep short for generation speed
MAX_NEW_TOKENS      = 256

SYSTEM_PROMPT = (
    "You are a highly knowledgeable and witty expert on energy, climate, and financial markets. "
    "Your answers must be **concise, technically accurate, and highly informative**, "
    "providing the core analysis necessary to fully address the user's prompt in a focused manner. "
    "Avoid unnecessary detail."
)

# ── Argument parsing ──────────────────────────────────────────────────────────
parser = argparse.ArgumentParser()
parser.add_argument("--model",  default=DEFAULT_MODEL_ID, help="Base model to use for rejected")
parser.add_argument("--limit",  type=int, default=None,   help="Limit number of examples (for testing)")
parser.add_argument("--output", default=OUTPUT_JSONL,     help="Output JSONL file")
args = parser.parse_args()

# ── Load base model ───────────────────────────────────────────────────────────
print(f"Loading base model: {args.model}")
bnb_config = BitsAndBytesConfig(
    load_in_4bit=True,
    bnb_4bit_quant_type="nf4",
    bnb_4bit_compute_dtype=torch.float16,
    bnb_4bit_use_double_quant=False,
)
tokenizer = AutoTokenizer.from_pretrained(args.model, trust_remote_code=True)
if tokenizer.pad_token is None:
    tokenizer.pad_token = tokenizer.eos_token

model = AutoModelForCausalLM.from_pretrained(
    args.model,
    quantization_config=bnb_config,
    device_map="auto",
    trust_remote_code=True,
)
model.eval()
print("Model loaded.\n")

# ── Load structured SFT data ─────────────────────────────────────────────────
with open(INPUT_JSONL, "r", encoding="utf-8") as f:
    examples = [json.loads(line) for line in f if line.strip()]

if args.limit:
    examples = examples[:args.limit]

print(f"Loaded {len(examples)} examples from {INPUT_JSONL}")

# ── Generate rejected responses ───────────────────────────────────────────────
def generate_rejected(prompt: str) -> str:
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user",   "content": prompt},
    ]
    try:
        text = tokenizer.apply_chat_template(
            messages, tokenize=False, add_generation_prompt=True
        )
    except Exception:
        text = f"<|system|>{SYSTEM_PROMPT}<|end|><|user|>{prompt}<|end|><|assistant|>"

    inputs = tokenizer(
        text,
        return_tensors="pt",
        truncation=True,
        max_length=MAX_SEQ_LENGTH,
    ).to(model.device)

    with torch.no_grad():
        out = model.generate(
            **inputs,
            max_new_tokens=MAX_NEW_TOKENS,
            do_sample=True,
            temperature=0.9,   # slightly higher → more generic/random
            top_p=0.95,
            pad_token_id=tokenizer.pad_token_id,
            eos_token_id=tokenizer.eos_token_id,
        )
    new_tokens = out[0][inputs["input_ids"].shape[-1]:]
    response = tokenizer.decode(new_tokens, skip_special_tokens=True).strip()
    return response


output_path = args.output
written = 0
skipped = 0

with open(output_path, "w", encoding="utf-8") as out_f:
    for ex in tqdm(examples, desc="Generating rejected responses"):
        prompt    = ex["prompt"]
        chosen    = ex["completion"]

        rejected  = generate_rejected(prompt)

        # Skip if rejected is identical to chosen (model memorised it)
        if rejected.strip() == chosen.strip() or len(rejected.strip()) < 10:
            skipped += 1
            continue

        record = {
            "prompt":   prompt,
            "chosen":   chosen,
            "rejected": rejected,
        }
        out_f.write(json.dumps(record, ensure_ascii=False) + "\n")
        written += 1

print(f"\nDone. Written: {written} | Skipped: {skipped}")
print(f"DPO dataset saved to: {output_path}")
